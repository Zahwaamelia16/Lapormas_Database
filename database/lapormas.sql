-- LAPORMAS database schema
-- DBMS: PostgreSQL

CREATE TABLE IF NOT EXISTS areas (
    area_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    village_name VARCHAR(150) NOT NULL,
    district_name VARCHAR(150) NOT NULL,
    regency_name VARCHAR(150) NOT NULL,
    boundary_geojson JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_areas_location UNIQUE (village_name, district_name, regency_name)
);

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'warga',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_role CHECK (role IN ('warga', 'petugas', 'admin'))
);

-- Email dibuat unik tanpa membedakan huruf besar/kecil.
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (LOWER(email));

-- Relasi users : user_profiles adalah one-to-one.
CREATE TABLE IF NOT EXISTS user_profiles (
    user_id BIGINT PRIMARY KEY,
    phone VARCHAR(30),
    address TEXT,
    village_name VARCHAR(150),
    area_id BIGINT,
    area_verification_status VARCHAR(20) NOT NULL DEFAULT 'menunggu',
    location_check_status VARCHAR(20) NOT NULL DEFAULT 'belum_diperiksa',
    location_checked_at TIMESTAMPTZ,
    CONSTRAINT fk_user_profiles_user
        FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_profiles_area
        FOREIGN KEY (area_id) REFERENCES areas(area_id) ON DELETE RESTRICT,
    CONSTRAINT chk_user_profiles_area_status
        CHECK (area_verification_status IN ('menunggu', 'terverifikasi', 'ditolak')),
    CONSTRAINT chk_user_profiles_location_status
        CHECK (location_check_status IN ('belum_diperiksa', 'sesuai', 'tidak_sesuai'))
);

CREATE TABLE IF NOT EXISTS report_categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS report_statuses (
    status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    status_id BIGINT NOT NULL,
    area_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    location TEXT NOT NULL,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reports_user
        FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_category
        FOREIGN KEY (category_id) REFERENCES report_categories(category_id) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_status
        FOREIGN KEY (status_id) REFERENCES report_statuses(status_id) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_area
        FOREIGN KEY (area_id) REFERENCES areas(area_id) ON DELETE RESTRICT,
    CONSTRAINT chk_reports_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_reports_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_reports_coordinate_pair
        CHECK ((latitude IS NULL AND longitude IS NULL) OR
               (latitude IS NOT NULL AND longitude IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS report_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    image_url TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_report_images_report
        FOREIGN KEY (report_id) REFERENCES reports(report_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS report_updates (
    update_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    old_status_id BIGINT,
    new_status_id BIGINT NOT NULL,
    notes TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_report_updates_report
        FOREIGN KEY (report_id) REFERENCES reports(report_id) ON DELETE CASCADE,
    CONSTRAINT fk_report_updates_user
        FOREIGN KEY (updated_by) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_report_updates_old_status
        FOREIGN KEY (old_status_id) REFERENCES report_statuses(status_id) ON DELETE RESTRICT,
    CONSTRAINT fk_report_updates_new_status
        FOREIGN KEY (new_status_id) REFERENCES report_statuses(status_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS responsible_units (
    unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_name VARCHAR(150) NOT NULL,
    description TEXT,
    contact VARCHAR(50),
    area_id BIGINT NOT NULL,
    CONSTRAINT fk_responsible_units_area
        FOREIGN KEY (area_id) REFERENCES areas(area_id) ON DELETE RESTRICT,
    CONSTRAINT uq_responsible_unit_per_area UNIQUE (unit_name, area_id)
);

-- Tabel penghubung reports dan responsible_units (many-to-many).
-- Nama kolom yang benar adalah report_id, bukan eport_id.
CREATE TABLE IF NOT EXISTS report_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assignment_notes TEXT,
    CONSTRAINT fk_report_assignments_report
        FOREIGN KEY (report_id) REFERENCES reports(report_id) ON DELETE CASCADE,
    CONSTRAINT fk_report_assignments_unit
        FOREIGN KEY (unit_id) REFERENCES responsible_units(unit_id) ON DELETE RESTRICT,
    CONSTRAINT uq_report_assignment UNIQUE (report_id, unit_id)
);

-- Index untuk mempercepat pencarian/filter data yang sering digunakan API.
CREATE INDEX IF NOT EXISTS idx_user_profiles_area_id ON user_profiles(area_id);
CREATE INDEX IF NOT EXISTS idx_reports_user_id ON reports(user_id);
CREATE INDEX IF NOT EXISTS idx_reports_category_id ON reports(category_id);
CREATE INDEX IF NOT EXISTS idx_reports_status_id ON reports(status_id);
CREATE INDEX IF NOT EXISTS idx_reports_area_id ON reports(area_id);
CREATE INDEX IF NOT EXISTS idx_reports_created_at ON reports(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reports_title_lower ON reports(LOWER(title));
CREATE INDEX IF NOT EXISTS idx_report_images_report_id ON report_images(report_id);
CREATE INDEX IF NOT EXISTS idx_report_updates_report_id ON report_updates(report_id);
CREATE INDEX IF NOT EXISTS idx_responsible_units_area_id ON responsible_units(area_id);
CREATE INDEX IF NOT EXISTS idx_report_assignments_report_id ON report_assignments(report_id);
CREATE INDEX IF NOT EXISTS idx_report_assignments_unit_id ON report_assignments(unit_id);

